#!/usr/bin/env node
/**
 * gate.test.js — 게이트 사전 회귀 테스트
 *
 * 실행: node content-pipeline/gate.test.js
 *
 * 왜 있나: 게이트 튜닝은 **두 방향으로** 틀릴 수 있는데 한쪽만 보기 쉽다.
 *   ① 오탐 — 정상 고지문을 위반으로 잡아 발행이 막힌다 (딜픽 83편 중 10편)
 *   ② 누락 — 부정 문맥 예외를 넓히다 진짜 위반까지 통과시킨다
 * babygrade 글은 「표시·사용 주의」 섹션에서 금지 표현을 **인용해 경고**하는 게 표준 구조라
 * ①을 막으려고 예외를 넓히면 ②로 조용히 넘어간다. 두 방향을 같이 고정한다.
 *
 * 사전(DICT)이나 NEGATION 을 고칠 때는 `node content-pipeline/gate.js --all` (오탐 0 유지) 과
 * 이 테스트(누락 0 유지) 를 **둘 다** 돌린다.
 */

const fs = require('fs');
const path = require('path');
const os = require('os');

// gate.js 는 실행 스크립트라 export 가 없다. main() 호출부만 빼고 로드한다.
const GATE = path.join(__dirname, 'gate.js');
const shim = path.join(os.tmpdir(), `gate-shim-${process.pid}.js`);
fs.writeFileSync(
  shim,
  fs.readFileSync(GATE, 'utf8').replace(/^main\(\);\s*$/m, 'module.exports = { DICT, findViolations };')
);
const { DICT, findViolations } = require(shim);
fs.unlinkSync(shim);

const D = {
  1: DICT.operator,
  2: DICT.emotive,
  3: DICT.medical,
  4: DICT.impersonation,
  5: DICT.fakePrice,
  13: DICT.absolute,
};

// [게이트번호, 이름, 문장, 기대]
// "위반" = 잡아야 한다 · "정상" = 통과시켜야 한다(대부분 실제 글의 고지·경고 문장 형태)
const CASES = [
  // ── #3 의약품 효능 (식약처) ──
  [3, '면역력 주장', '이 유산균을 매일 먹이면 면역력 강화에 확실히 도움이 됩니다.', '위반'],
  [3, '면역력 고지', '"면역력 강화" 같은 효능 단정은 식약처 표시광고법상 쓸 수 없다.', '정상'],
  [3, '발달 촉진 주장', '성분 배합이 두뇌 발달을 촉진합니다.', '위반'],
  [3, '발달 촉진 고지', '"발달 촉진" 은 인정되지 않은 표현이라 광고에 쓸 수 없다.', '정상'],
  [3, '치료 주장', '이 복대는 임신 중 요통을 치료합니다.', '위반'],
  [3, '치료 고지', '어떤 유형이든 요통을 치료하지 않으며 과압박 회피가 함께 가야 한다.', '정상'],
  [3, '통잠 주장', '밤에 켜두면 아기가 통잠을 잡니다.', '위반'],
  [3, '통잠 고지', '"통잠"·"꿀잠" 같은 효과 단정은 광고에서 금지된다.', '정상'],
  [3, '돌연사 예방 고지', '"영아 돌연사 예방" 을 단정하는 표현은 쓸 수 없다.', '정상'],

  // ── #13 절대적 안전 표현 (영유아 특화) ──
  [13, '100% 안전 주장', '이 소재는 100% 안전한 국내산 원료입니다.', '위반'],
  [13, '100% 안전 고지', '"100% 안전" 같은 절대적 표현은 사용이 금지된다.', '정상'],
  [13, '부작용 없음 주장', '지금까지 부작용이 없는 안전한 제품입니다.', '위반'],
  [13, '부작용 없음 고지', '"부작용이 없다" 고 단정하는 표현은 광고에서 금지된다.', '정상'],
  [13, '절대 무해 주장', '절대 무해한 원료만 사용했습니다.', '위반'],
  [13, '완벽 차단 주장', '이 필터는 세균을 완벽 차단합니다.', '위반'],

  // ── #4 쿠팡 사칭 ──
  [4, '사칭 주장', '본 제품은 쿠팡 공식 추천 1위에 선정됐습니다.', '위반'],
  [4, '사칭 고지', '"쿠팡 공식 추천" 처럼 플랫폼을 사칭하는 표현은 약관 위반이다.', '정상'],

  // ── #5 가짜 정가·최저가 단정 ──
  [5, '최저가 보장 주장', '저희는 항상 최저가 보장을 약속드립니다.', '위반'],
  [5, '정가 대비 주장', '정가 89,000원 → 특가로 판매 중입니다.', '위반'],
  [5, '최저가 고지', '"최저가 보장" 은 실시간 가격 변동 탓에 쓸 수 없는 표현이다.', '정상'],

  // ── #1 허위 사용 후기 (부정 문맥 예외 없음 — 노출 자체가 문제) ──
  [1, '허위 후기 주장', '우리 아이가 직접 써봤는데 만족스러웠습니다.', '위반'],
  [1, '정상 표현', '우리 아이에게 맞는 사이즈를 고르는 것이 중요하다.', '정상'],

  // ── #2 감성어 (톤) ──
  [2, '감성어', '디자인이 너무 예쁘고 강추합니다.', '위반'],
  [2, '중립 서술', '디자인은 단순한 편이고 마감은 무난한 수준으로 판단된다.', '정상'],
];

let pass = 0;
const failures = [];
for (const [n, name, text, expect] of CASES) {
  // #1 은 부정 문맥 예외를 두지 않는 게이트라 gate.js 와 같게 matchAll 로 본다
  const hits =
    n === 1
      ? (text.match(new RegExp(D[1].source, D[1].flags)) || []).length > 0
      : findViolations(text, D[n], []).length > 0;
  const got = hits ? '위반' : '정상';
  if (got === expect) pass++;
  else failures.push(`  ✗ #${n} ${name} — 기대 ${expect} / 결과 ${got}\n     "${text}"`);
}

console.log(`게이트 사전 회귀 테스트: ${pass}/${CASES.length} 통과`);
if (failures.length) {
  console.log('\n' + failures.join('\n'));
  console.log(
    '\n누락(위반→정상)이면 NEGATION 이 너무 넓다. 오탐(정상→위반)이면 사전이 너무 넓다.'
  );
  process.exit(1);
}
console.log('오탐·누락 0 — 사전과 부정 문맥 예외가 양방향으로 고정됐다.');
